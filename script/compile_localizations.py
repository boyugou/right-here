#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# ///
"""Compile Localization/Localizable.xcstrings into Swift.

The catalog is the source of truth for every user-visible string. The command-line tool lives
inside the app bundle and cannot load a resource bundle, so the strings are compiled into
Sources/RightHereCore/Localization/Localizations.generated.swift and read from there by the
menu, the app and the alerts alike.

    ./script/compile_localizations.py            write the Swift file
    ./script/compile_localizations.py --check    fail if the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "Localization" / "Localizable.xcstrings"
OUTPUT = ROOT / "Sources" / "RightHereCore" / "Localization" / "Localizations.generated.swift"


def swift_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")
    )
    return f'"{escaped}"'


def render(catalog: dict) -> str:
    strings = catalog["strings"]
    languages = sorted({lang for entry in strings.values() for lang in entry["localizations"]}, key=lambda l: (l != "en", l))
    lines = [
        "// Generated by script/compile_localizations.py from Localization/Localizable.xcstrings. Do not edit.",
        "",
        "enum Localizations {",
        "    static let languages: [String] = [" + ", ".join(swift_string(l) for l in languages) + "]",
        "",
        "    static let table: [String: [String: String]] = [",
    ]
    for key in sorted(strings):
        lines.append(f"        {swift_string(key)}: [")
        for lang in languages:
            unit = strings[key]["localizations"].get(lang, {}).get("stringUnit")
            if unit is not None:
                lines.append(f"            {swift_string(lang)}: {swift_string(unit['value'])},")
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main() -> int:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    text = render(catalog)
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run ./script/compile_localizations.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
