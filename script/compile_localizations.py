#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# ///
"""Compile the String Catalog into Swift.

Localization/Localizable.xcstrings is the source of truth for the strings the code says and Localization/languages.json
for the languages. The command-line tool lives inside the app bundle and cannot load a resource bundle, so the strings
are compiled into Swift (Sources/RightHereCore/Localization/) and read from there by the menu, the app, the alerts and
the doctor alike. The catalogs that only the app reads from its bundle by key (AppIntents.xcstrings: what the App Intents
are called, AppShortcuts.xcstrings, InfoPlist.xcstrings) are not compiled: a key of theirs would be a case no code reads.

    Localizations.generated.swift      the languages and the table of every text
    LocalizationKey.generated.swift    one case per catalog key, and how many arguments its text takes
    LocalizedMessage.generated.swift   a typed constructor per key, so a wrong number of arguments does not compile

    ./script/compile_localizations.py            write the Swift files
    ./script/compile_localizations.py --check    fail if one of them is out of date
"""
import re
import sys

from localization_lib import ROOT, SWIFT_DIRECTORY, arity, case_name, languages, read_catalog, swift_string

BANNER = "// Generated by script/compile_localizations.py from Localization/Localizable.xcstrings. Do not edit."
IDENTIFIER = re.compile(r"^[a-z][A-Za-z0-9]*$")


def english_texts(catalog: dict) -> dict[str, str]:
    return {key: entry["localizations"]["en"]["stringUnit"]["value"] for key, entry in sorted(catalog["strings"].items())}


def validated(catalog: dict) -> dict[str, tuple[str, int]]:
    """For every key its Swift name and arity, or an error that says which key is wrong."""
    names: dict[str, str] = {}
    result: dict[str, tuple[str, int]] = {}
    problems = []
    for key, english in english_texts(catalog).items():
        name = case_name(key)
        if len(key.split(".")) < 2 or not IDENTIFIER.match(name):
            problems.append(f"{key}: a key has two or more dotted parts and becomes a Swift name like menuOpenIn (got {name!r})")
            continue
        if name in names:
            problems.append(f"{key}: becomes {name}, which {names[name]} already is")
            continue
        names[name] = key
        try:
            result[key] = (name, arity(english))
        except ValueError as error:
            problems.append(f"{key}: the English text {error}")
    if problems:
        raise SystemExit("\n".join(problems))
    return result


def render_table(catalog: dict) -> str:
    """The languages, one dictionary per key, and the table that gathers them.

    The texts are not written as one nested literal: the initializer of a `[String: [String: String]]` literal that
    holds every text (157 keys x 30 languages) never finishes in a release build with Swift 6.3.2 (the COWArrayOpts
    pass of the optimizer, in ColdBlockInfo::analyze; measured on macOS 26.5, the command-line tools of Xcode 26.5).
    A dictionary per key, each a small literal, compiles the module in under half a minute.
    """
    strings = catalog["strings"]
    names = validated(catalog)
    codes = [language.code for language in languages()]
    lines = [
        BANNER,
        "",
        "enum Localizations {",
        "    static let languages: [String] = [" + ", ".join(swift_string(code) for code in codes) + "]",
        "",
        "    // One literal with every text in it hangs the optimizer of Swift 6.3 (see script/compile_localizations.py).",
        "    static let table: [String: [String: String]] = [",
    ]
    for key in sorted(strings):
        lines.append(f"        {swift_string(key)}: {names[key][0]},")
    lines.append("    ]")
    for key in sorted(strings):
        lines += ["", f"    private static let {names[key][0]}: [String: String] = ["]
        for code in codes:
            unit = strings[key]["localizations"].get(code, {}).get("stringUnit")
            if unit is not None:
                lines.append(f"        {swift_string(code)}: {swift_string(unit['value'])},")
        lines.append("    ]")
    lines += ["}", ""]
    return "\n".join(lines)


def render_keys(catalog: dict) -> str:
    keys = validated(catalog)
    lines = [
        BANNER,
        "",
        "/// One case per entry of the String Catalog; the raw value is the catalog key. `LocalizedMessage` has a typed",
        "/// constructor for each of them.",
        "public enum LocalizationKey: String, Sendable, CaseIterable {",
    ]
    for key, (name, _) in keys.items():
        lines.append(f"    case {name} = {swift_string(key)}")
    lines += ["", "    /// How many arguments the English text takes: its `%@` placeholders, or the highest `%n$@`.", "    public var arity: Int {", "        switch self {"]
    for count in sorted({count for _, count in keys.values() if count > 0}):
        names = ", ".join(f".{name}" for name, number in keys.values() if number == count)
        lines.append(f"        case {names}: {count}")
    lines += ["        default: 0", "        }", "    }", "}", ""]
    return "\n".join(lines)


def render_messages(catalog: dict) -> str:
    keys = validated(catalog)
    english = english_texts(catalog)
    lines = [BANNER, "", "extension LocalizedMessage {"]
    for key, (name, count) in keys.items():
        lines.append(f"    /// {english[key].replace(chr(10), ' ')}")
        if count == 0:
            lines.append(f"    public static var {name}: LocalizedMessage {{ LocalizedMessage(.{name}) }}")
        else:
            parameters = ", ".join(f"_ argument{number}: String" for number in range(1, count + 1))
            arguments = ", ".join(f"argument{number}" for number in range(1, count + 1))
            lines.append(f"    public static func {name}({parameters}) -> LocalizedMessage {{ LocalizedMessage(.{name}, [{arguments}]) }}")
    lines += ["}", ""]
    return "\n".join(lines)


def outputs(catalog: dict) -> dict:
    return {
        SWIFT_DIRECTORY / "Localizations.generated.swift": render_table(catalog),
        SWIFT_DIRECTORY / "LocalizationKey.generated.swift": render_keys(catalog),
        SWIFT_DIRECTORY / "LocalizedMessage.generated.swift": render_messages(catalog),
    }


def main() -> int:
    files = outputs(read_catalog("Localizable.xcstrings"))
    if "--check" in sys.argv:
        stale = [path for path, text in files.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date; run ./script/compile_localizations.py", file=sys.stderr)
        return 1 if stale else 0
    SWIFT_DIRECTORY.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
